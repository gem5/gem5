// The hardware sequence is correctly rounded, so for random operands the
// result must equal the host's IEEE quotient.
TEST(VegaFp32DivTest, DivisionSequenceIsCorrectlyRounded)
{
    std::mt19937 rng(1);
    std::uniform_real_distribution<float> mantissa(1.0f, 2.0f);
    std::uniform_int_distribution<int> exponent(-20, 20);
    int errors = 0;
    for (int i = 0; i < (1 << 20); ++i) {
        float a, b;
        if (i % 2) {
            // Ordinary operands within a few orders of magnitude.
            a = std::ldexp(mantissa(rng), exponent(rng));
            b = std::ldexp(mantissa(rng), exponent(rng));
        } else {
            // Any finite bit patterns, including subnormals.
            do {
                a = f(rng());
                b = f(rng());
            } while (!std::isfinite(a) || !std::isfinite(b));
        }
        const float want = a / b;
        const float got = divide(a, b);
        if (std::isnan(want) ? !std::isnan(got)
                             : f32ToBits(got) != f32ToBits(want)) {
            if (errors++ < 10) {
                ADD_FAILURE() << std::hex << f32ToBits(a) << " / "
                              << f32ToBits(b) << " = " << f32ToBits(got)
                              << ", expected " << f32ToBits(want);
            }
        }
    }
    EXPECT_EQ(errors, 0);
}
