// The sequence the compiler emits for an FP32 '/' with denormals enabled.
float
divide(float a, float b)
{
    bool vcc;
    const float sb = divScaleF32(b, b, a, vcc);
    const float sa = divScaleF32(a, b, a, vcc);
    const float r0 = rcpF32(sb);
    const float t1 = std::fma(-sb, r0, 1.0f);
    const float r1 = std::fma(t1, r0, r0);
    const float q0 = sa * r1;
    const float t2 = std::fma(-sb, q0, sa);
    const float q1 = std::fma(t2, r1, q0);
    const float res = std::fma(-sb, q1, sa);
    return divFixupF32(divFmasF32(res, r1, q1, vcc), b, a);
}

