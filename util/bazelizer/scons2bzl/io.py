"""BUILD file writer and utilities."""

import logging
import os

from scons2bzl import types

GENERATED_FILE_MARKER = "# GENERATED BY @bazelize_gem5//scons2bzl:sync"
NEW_FILE_TEMPLATE = """
# See "build_tools/bazel/README.md" when in doubt
load("@bazel_skylib//rules:common_settings.bzl", "bool_flag", "string_flag", "int_flag")
load(
    "//build_tools/bazel:rules.bzl",
    "gem5_py_source",
    "gen_config",
    "debug_flag",
    "COMMON_COPTS",
    "COMMON_LINKOPTS",
)
load("//build_tools/bazel:macro.bzl", "macro_sim_object", "macro_py_source")

cc_library(
    name = "lib",
    deps = [
# OBJS_GOES_HERE.START
# OBJS_GOES_HERE.END
    ],
    visibility = ["//build_tools/bazel/package_group:simulator"],
)

sim_objects = [
# SIMOBJ_GOES_HERE.START
# SIMOBJ_GOES_HERE.END
]

cc_library(
    name = "sim_objects",
    deps = sim_objects + [
# SIMOBJ_LIB_GOES_HERE.START
# SIMOBJ_LIB_GOES_HERE.END
    ],
    visibility = ["//build_tools/bazel/package_group:simulator"],
)

# DEBUG_FLAG_GOES_HERE.START
# DEBUG_FLAG_GOES_HERE.END

# TARGET_GOES_HERE.START
# TARGET_GOES_HERE.END
""".lstrip()
