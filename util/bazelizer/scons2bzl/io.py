def new_file_template(file: str) -> None:
    new_content = "\n".join([GENERATED_FILE_MARKER, NEW_FILE_TEMPLATE])
    if not os.path.isdir(os.path.dirname(file)):
        os.makedirs(os.path.dirname(file))
    with open(file, "w") as f:
        f.write(new_content)


def update_build(
    build_file: types.Path,
    marker: str,
    content: str,
    append: bool = True,
    no_error: bool = False,
) -> None:
    """The utility to create/update a generated BUILD file.

    This function assumes the template contains several insertion points
    indicated by `marker`.  For example, a generated BUILD file may contain
    something like:

    ```
    # ... contents before the insertion point ...
    # MY_MARKER.START
    # MY_MARKER.END
    # ... contents after the insertion point ...
    ```

    Args:
        build_file: Path to the build_file.
        marker: Indicator of the location in the file where `content` should be
          injected.
        content: The content to be written.
        append: Overwrite the file if `False`.
        no_error: Do nothing on error.

    Raises:
        ValueError: If the `marker` indicating the location to inject `context`
          cannot be found.
    """
    build_file = build_file.abs
    if not os.path.isfile(build_file):
        new_file_template(build_file)
    with open(build_file) as f:
        lines = f.readlines()
    try:
        start = lines.index(f"# {marker}.START\n")
        end = lines.index(f"# {marker}.END\n")
    except ValueError:
        if no_error:
            return
        logging.error("Error updating %s", build_file)
        raise
    if content:
        content_lines = [content + "\n"]
    else:
        content_lines = []
    begin = end if append else start + 1
    new_content = "".join(lines[:begin] + content_lines + lines[end:])
    with open(build_file, "w") as f:
        f.write(new_content)


def remove_if_generated(file: types.Path) -> None:
    with open(file.abs) as f:
        is_generated = f.readline().startswith(GENERATED_FILE_MARKER)
    if is_generated:
        os.remove(file.abs)
